export function cleanLabel(t) { return String(t || "").toUpperCase().replace(/[^A-Z0-9 \-./+']/g, "").replace(/\s+/g, " ").trim().slice(0, LABEL.maxLen); }
export function labelAdvance(ch) { return ch === " " ? SPACE_ADV : GLYPH_ADV; }
export function labelUnits(text) { var u = 0; for (var i = 0; i < text.length; i++) u += labelAdvance(text[i]); return u - (GLYPH_ADV - GLYPH_W); }
export function strokeFor(cap) { return Math.min(0.9, Math.max(0.45, cap * 0.22)); } // one or two nozzle widths, scaled with the letters
